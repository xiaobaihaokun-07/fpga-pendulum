"""Generate the standalone native 208x156 DVP reference register ROM.

The original STMicroelectronics OV5640_Common table, upstream file SHA256s,
and complete BSD-3-Clause license are retained in
third_party/appnote_reference_regs.json. This is an adapted reference profile,
not an unmodified ST or OmniVision preset and not a proven hardware fix.

Readout window and the complete CIP group follow OmniVision's parallel
application note sections 4.1.1/4.1.2. Output dimensions are 208x156.
Retain the verified 19.2 MHz SYSCLK and 2.4 MHz DVP PCLK, with HTS=4000.
No Espressif-specific 4514/4520 patch is carried into this reset-based profile.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).absolute().parent
SOURCE = ROOT / "third_party/appnote_reference_regs.json"
OUTPUT = ROOT / "src/ov5640_reference_rom.v"


def pairs(text):
    tokens = text.split()
    assert len(tokens) % 2 == 0
    return [(int(a, 16), int(v, 16)) for a, v in zip(tokens[::2], tokens[1::2])]


# Parallel application note, VGA readout geometry. Only the DVP output width
# and height change from 640x480 to 208x156; automatic scaling stays enabled.
WINDOW = pairs("""
    3820 41 3821 07 3814 31 3815 31
    3800 00 3801 00 3802 00 3803 04 3804 0a 3805 3f 3806 07 3807 9b
    3808 00 3809 d0 380a 00 380b 9c
    380c 0f 380d a0 380e 03 380f d8
    3810 00 3811 10 3812 00 3813 06
    3618 00 3612 29 3708 64 3709 52 370c 03
    4001 02 4004 02 4005 1a
""")

# Full CIP group from the parallel application note. The note leaves 5308 at
# its documented reset value 25 (OV5640 datasheet, CIP control table).
# Write it explicitly: ST Common's last CIP entries differ from this group.
CIP = pairs("""
    5300 08 5301 30 5302 10 5303 00 5304 08 5305 30 5306 08
    5307 16 5308 25 5309 08 530a 30 530b 04 530c 06
""")

# At nominal 24 MHz XVCLK: VCO=192 MHz, PLL_CLK=76.8 MHz,
# SYS=19.2 MHz and PCLK=76.8/2/16=2.4 MHz. Clock equations:
# https://github.com/espressif/esp32-camera/blob/master/sensors/ov5640.c
# 416 output bytes take 173.3us; HTS4000/SYS gives a 208.3us source line.
# This is a timing budget, not a measurement of the sensor FIFO or crystal.
# Preserve the physically tested PCLK and external sampling configuration.
CLOCK = pairs("""
    3034 1a 3035 11 3036 08 3037 01 3039 00 3108 16
    3824 10 460c 22 3103 13
""")

# AE mains-light rejection uses SYS clocks per line, not the DVP byte clock.
# For nominal SYS=19.2 MHz and HTS=4000: floor(SYS/HTS/100)=48,
# floor(SYS/HTS/120)=40; floor(VTS/step)=20/24. Bound the shutter to
# the configured 984-line frame instead of inheriting a faster-clock mode.
EXPOSURE = pairs("""
    3a02 03 3a03 d8 3a14 03 3a15 d8
    3a08 00 3a09 30 3a0a 00 3a0b 28 3a0d 18 3a0e 14
""")

# Explicit board/output adaptation. ROM defaults to big-endian RGB565;
# camera_init's FORMAT_COMPARE override can select YUYV without other changes.
# 5003=08 is its documented reset value. 4741=00 disables DVP-generated test
# output; camera_init controls the independent PRE_ISP 503D colorbar latch.
OUTPUT_CONTROL = pairs("""
    3017 ff 3018 ff 302c c3
    3000 00 3002 1c 3004 ff 3006 c3 300e 58 302e 00
    4300 61 501f 01 4713 03 4407 04 440e 00 460b 35
    4740 23 4741 00 5000 a7 5001 a3 5003 08
    3406 00 3503 00 503d 00
""")


def registers():
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    common = [(int(a, 16), int(v, 16)) for a, v in source["pairs"]]
    assert len(common) == 246
    assert common[:3] == [(0x3103, 0x11), (0x3008, 0x82), (0x3103, 0x03)]
    assert common[-1] == (0x3008, 0x02)
    # Hardware reset is handled by camera_init. Select pad clock before SW
    # reset, wait 100ms, then keep standby asserted for every setup write.
    result = common[:2] + [(0xFFFF, 100), (0x3008, 0x42)] + common[2:-1]
    result += WINDOW + CIP + CLOCK + EXPOSURE + OUTPUT_CONTROL
    result += [(0x3008, 0x02), (0xFFFF, 300)]
    final = dict(result)
    assert 0x4514 not in final and 0x4520 not in final
    assert all(0x5800 + i in final for i in range(0x3E))  # full LENC table
    assert final[0x5580] == 0x02 and final[0x5308] == 0x25
    assert (final[0x3808] << 8 | final[0x3809]) == 208
    assert (final[0x380A] << 8 | final[0x380B]) == 156
    assert (final[0x380C] << 8 | final[0x380D]) == 4000
    assert (final[0x380E] << 8 | final[0x380F]) == 984
    assert len(result) < 512
    assert all(0 <= a <= 0xFFFF and 0 <= v <= (0xFFFF if a == 0xFFFF else 0xFF)
               for a, v in result)
    return result


def render():
    entries = registers()
    lines = [
        "// Generated by generate_reference_init.py; do not hand-edit.",
        "// Derived from STMicroelectronics OV5640_Common (BSD-3-Clause).",
        "// Copyright 2019(-2020) STMicroelectronics. All rights reserved.",
        "// Full license/source hashes: third_party/appnote_reference_regs.json.",
        "// Native 208x156, SYS19.2/PCLK2.4, HTS4000: see generator.",
        "// word: address[31:16], data/delay_ms[15:0]. FFFF denotes a delay.",
        "module ov5640_reference_rom(input wire [8:0] index, output reg [31:0] word, output wire last);",
        "    localparam integer ENTRY_COUNT = %d;" % len(entries),
        "    assign last=index==ENTRY_COUNT;",
        "    always @* case(index)",
    ]
    lines.extend("        9'd%d: word=32'h%04x%04x;" % (i, a, v)
                 for i, (a, v) in enumerate(entries))
    lines.extend(["        default: word=0;", "    endcase", "endmodule", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated ROM without writing")
    parser.add_argument("--dump", action="store_true", help="print final writable register map")
    args = parser.parse_args()
    if args.dump:
        print(json.dumps({f"{a:04X}": f"{v:02X}" for a, v in sorted(dict(registers()).items())
                          if a != 0xFFFF}, indent=2))
    elif args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != render():
            raise SystemExit("Reference ROM differs from generator; rerun generate_reference_init.py")
        print("PASS: reference ROM matches %d register/delay entries" % len(registers()))
    else:
        OUTPUT.write_text(render(), encoding="utf-8")
        print("Generated %d register/delay entries: %s" % (len(registers()), OUTPUT))
